import { useLoaderData } from 'react-router';
import type { TotpEnrollment } from '../api';
import { MfaShell, TotpCodeForm } from '../components/MfaShell';

export type MfaSetupData = { next: string; enrollment: TotpEnrollment };

/** /admin/mfa/setup: first admin sign-in registers an authenticator app, then checks one code. */
export function MfaSetupPage() {
  const { next, enrollment } = useLoaderData<MfaSetupData>();
  return (
    <MfaShell title="인증 앱 등록">
      <p className="text-sm">인증 앱으로 QR 코드를 스캔하거나 아래 키를 입력하세요.</p>
      <div className="flex flex-col items-start gap-4">
        {/* SVG data URI generated by Supabase Auth for this enrolment. */}
        <img
          src={enrollment.qrCode}
          alt="인증 앱 등록 QR 코드"
          width={176}
          height={176}
          className="size-44 border border-line bg-white"
        />
        <div className="flex flex-col gap-1">
          <span className="text-xs text-ink-muted">키</span>
          <code className="text-sm break-all select-all">{enrollment.secret}</code>
        </div>
      </div>
      <TotpCodeForm factorId={enrollment.factorId} next={next} submitLabel="등록" />
    </MfaShell>
  );
}
